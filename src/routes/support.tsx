import { createFileRoute, Link, useNavigate } from "@tanstack/react-router";
import { Bot, CheckCircle2, MessageSquare, RotateCcw, XCircle, HeartHandshake } from "lucide-react";
import { useMemo, useState } from "react";
import mascot from "@/assets/mascot.png";
import { CodeBlock, EmptyState, PageHeader, Panel } from "@/components/AppShell";
import { Button } from "@/components/ui/button";
import { startQuiz } from "@/lib/actions";
import { allQuestions } from "@/lib/questions";
import { useStore } from "@/lib/store";
import { CONCEPTS, codeExample, getSubject, titleCase } from "@/lib/subjects";

export const Route = createFileRoute("/support")({
  head: () => ({
    meta: [
      { title: "Tutor explanation — LearnMate AI" },
      { name: "description", content: "Beginner-friendly explanations, analogies, code and practice for your weak concepts." },
      { property: "og:title", content: "Tutor explanation — LearnMate AI" },
      { property: "og:description", content: "Personalised help for the concepts you found tricky." },
    ],
  }),
  component: Support,
});

function Support() {
  const { attempts } = useStore();
  const navigate = useNavigate();
  const a = attempts.at(-1);
  const weak = a?.wrongConcepts ?? [];

  const practice = useMemo(() => {
    if (!a) return [];
    const seen = new Set(a.questionIds);
    const pool = allQuestions(a.subject, "easy").filter((q) => !seen.has(q.id));
    const focused = pool.filter((q) => weak.includes(q.concept));
    return [...focused, ...pool].slice(0, 2);
  }, [a?.id]);
  const [picks, setPicks] = useState<Record<string, number>>({});

  if (!a || !weak.length) return <EmptyState icon={<HeartHandshake />} title="No weak concepts to review" text="Take a quiz first — if anything is tricky, your personalised explanation appears here." action={<Button asChild variant="hero"><Link to="/learn">Start Learning</Link></Button>} />;
  const subj = getSubject(a.subject)!;

  return (
    <div className="space-y-6">
      <PageHeader eyebrow="AI Tutor · Demo mode" title="Let's learn this together" subtitle={`Simple explanations for the ${subj.name} concepts you missed. Take your time.`}>
        <img src={mascot} alt="" width={1024} height={1024} className="hidden w-24 animate-float md:block" />
      </PageHeader>
      <p className="rounded-xl border border-warning/40 bg-warning/10 p-3 text-xs text-warning">DEMO MODE — these explanations are pre-written, rule-based content, not generated by a live AI model.</p>

      {weak.map((c) => (
        <Panel key={c}>
          <h2 className="text-2xl font-semibold text-gradient">{titleCase(c)}</h2>
          <p className="mt-3">{CONCEPTS[c]?.simple}</p>
          <div className="mt-4 rounded-xl bg-accent/50 p-4"><p className="text-sm"><b>🌍 Real-world analogy:</b> {CONCEPTS[c]?.analogy}</p></div>
          <p className="mb-2 mt-4 text-sm font-semibold">Small code example</p>
          <CodeBlock code={codeExample(a.subject, c)} />
        </Panel>
      ))}

      <Panel>
        <h2 className="text-xl font-semibold">Two practice questions</h2>
        <div className="mt-4 space-y-6">
          {practice.map((q, n) => {
            const pick = picks[q.id];
            return (
              <div key={q.id}>
                <p className="font-medium">{n + 1}. {q.text}</p>
                {q.code && <div className="mt-2"><CodeBlock code={q.code} /></div>}
                <div className="mt-3 grid gap-2 sm:grid-cols-2">
                  {q.options.map((o, i) => {
                    const state = pick === undefined ? "" : i === q.answer ? "border-success bg-success/15" : i === pick ? "border-destructive bg-destructive/15" : "opacity-60";
                    return <button key={i} disabled={pick !== undefined} onClick={() => setPicks((p) => ({ ...p, [q.id]: i }))} className={`rounded-xl border border-border bg-muted/40 p-3 text-left font-mono text-sm transition ${state}`}>{o}</button>;
                  })}
                </div>
                {pick !== undefined && (
                  <p className={`mt-2 flex items-center gap-2 text-sm ${pick === q.answer ? "text-success" : "text-destructive"}`}>
                    {pick === q.answer ? <CheckCircle2 className="size-4" /> : <XCircle className="size-4" />} {pick === q.answer ? "Correct!" : "Not quite."} <span className="text-muted-foreground">{q.explanation}</span>
                  </p>
                )}
              </div>
            );
          })}
        </div>
      </Panel>

      <div className="flex flex-wrap gap-3">
        <Button variant="hero" size="lg" onClick={() => { startQuiz(a.subject, a.topic, a.level, weak, true); navigate({ to: "/quiz" }); }}><RotateCcw /> Retake quiz on weak concepts</Button>
        <Button asChild variant="glass" size="lg"><Link to="/tutor"><MessageSquare /> Ask the tutor a question</Link></Button>
        <Button asChild variant="glass" size="lg"><Link to="/plan"><Bot /> View study plan</Link></Button>
      </div>
    </div>
  );
}
